function createBombs(
  specs: (BombSeedSpec & { grooveOverride?: EngravingGrooveKind; pairedSoapOverride?: string })[],
): BathBombCreation[] {
  return specs.map((spec, idx) => {
    const grooveStyle = spec.grooveOverride ?? BOMB_GROOVE_ROTATION[idx % BOMB_GROOVE_ROTATION.length];
    const grooveMeta = GROOVE_SPECS[grooveStyle];
    const lineSoaps = PAIRED_SOAP_IDS_BY_LINE[spec.line] ?? PAIRED_SOAP_IDS_BY_LINE.bright;
    const pairedSoapId = spec.pairedSoapOverride ?? lineSoaps[idx % lineSoaps.length];

    return {
      id: spec.id,
      line: spec.line,
      editionNumber: spec.editionNumber,
      nameEn: spec.nameEn,
      nameTh: spec.nameTh,
      soakMoodEn: spec.soakMoodEn,
      soakMoodTh: spec.soakMoodTh,
      heroActivesEn: spec.heroActivesEn,
      heroActivesTh: spec.heroActivesTh,
      brighteningNoteEn: spec.brighteningNoteEn,
      brighteningNoteTh: spec.brighteningNoteTh,
      highlightsEn: spec.highlightsEn,
      highlightsTh: spec.highlightsTh,
      waterHueNameEn: spec.waterHueNameEn,
      waterHueNameTh: spec.waterHueNameTh,
      waterHueHex: spec.waterHueHex,
      waterGradient: spec.waterGradient,
      fizzDurationEn: `2.5–3.5 min Fast-Dissolve · ${grooveMeta.shortEn}`,
      fizzDurationTh: `2.5–3.5 นาที ละลายไว · ${grooveMeta.shortTh}`,
      soakTemp: '38–40°C',
      edibleGoldLeaf: spec.edibleGoldLeaf,
      grooveStyle,
      grooveLabelEn: grooveMeta.en,
      grooveLabelTh: grooveMeta.th,
      halfSplitEn: `Transparent Mineral Bath Salt Crystals + ${spec.waterHueNameEn} Pressed Sphere · ${grooveMeta.shortEn}`,
      halfSplitTh: 'เกลืออาบน้ำคริสตัลใสแท้ผสานแร่ธาตุธรรมชาติ · ก้อนอัดร่องแกะสลัก 3 มิติ',
      gentleBubbleSeal: 'GentleBubble',
      pairedSoapId,
      nutrientFocus: spec.nutrientFocus,
      brighteningScore: spec.brighteningScore,
      scentIntensity: spec.scentIntensity,
      imageUrl: spec.imageUrl,
      imageAlt: `${spec.nameEn} bath bomb studded with transparent mineral bath salt crystals, engraved GentleBubble, ${grooveMeta.en}, and ${spec.edibleGoldLeaf === 'rose-gold' ? '24k rose gold leaf' : '24k yellow gold leaf'}`,
      fallbackGradient: spec.fallbackGradient,
      priceThb: BATH_BOMB_PRICE_TIERS.single,
      nutritionPack: buildNutritionPack(spec),
    };
  });
}

